#!/usr/bin/env bash
# Remote-MCP: Colab/Linux Agent installer from HTTPS Render.
set -euo pipefail
umask 077
BASE_URL='__KRW_PUBLIC_ORIGIN__'
EXPECTED_SHA256='__KRW_AGENT_BUNDLE_SHA256__'
INSTALL_DIR="${KRW_INSTALL_DIR:-$HOME/.local/share/krw-agent}"
CONFIG_DIR="${KRW_CONFIG_DIR:-$HOME/.config/krw-agent}"

fail() { printf 'KRW setup ERROR: %s\n' "$*" >&2; exit 1; }
info() { printf '[KRW] %s\n' "$*" >&2; }
prompt() {
  local __name="$1" __message="$2" __answer=''
  [[ -r /dev/tty ]] || fail 'No terminal: set KRW_WORKSPACE_ROOT as an environment variable.'
  IFS= read -r -p "$__message" __answer </dev/tty || fail 'Input cancelled'
  printf -v "$__name" '%s' "$__answer"
}

[[ "$BASE_URL" == https://* && "$BASE_URL" != *'__KRW_'* ]] || fail 'Bootstrap URL not configured'
[[ "$EXPECTED_SHA256" =~ ^[a-f0-9]{64}$ ]] || fail 'Invalid archive digest'
command -v python3 >/dev/null || fail 'Python 3 is required'
command -v tar >/dev/null || fail 'tar is required'
command -v sha256sum >/dev/null || fail 'sha256sum is required'
python3 -c 'import sys; assert sys.version_info >= (3,10), "Python 3.10+ required"' \
  || fail 'Python 3.10 or newer is required'

# Reuse an existing, owner-controlled Agent configuration on upgrades. Explicit
# environment values override stored settings. This avoids re-entering secrets.
CONFIG_FILE="$CONFIG_DIR/agent.env"
OVERRIDE_DEVICE_ID="${KRW_DEVICE_ID:-}"
OVERRIDE_WORKSPACE="${KRW_WORKSPACE_ROOT:-}"
OVERRIDE_TOKEN="${KRW_AGENT_TOKEN:-}"
OVERRIDE_AUTO_ENROLL="${KRW_AUTO_ENROLL:-}"
OVERRIDE_WRITES="${KRW_ALLOW_FILE_WRITES:-}"
OVERRIDE_CHECKS="${KRW_ALLOW_STATIC_CHECKS:-}"
OVERRIDE_WORKSPACES="${KRW_WORKSPACES_JSON:-}"
OVERRIDE_GIT_WRITES="${KRW_ALLOW_GIT_WRITES:-}"
OVERRIDE_GIT_PUSH="${KRW_ALLOW_GIT_PUSH:-}"
OVERRIDE_TASKS="${KRW_ALLOW_TASKS:-}"
OVERRIDE_TEST_TASKS="${KRW_ALLOW_TEST_TASKS:-}"
OVERRIDE_LONG_TASKS="${KRW_ALLOW_LONG_TASKS:-}"
OVERRIDE_CLI="${KRW_ALLOW_CLI:-}"
OVERRIDE_GIT_TOKEN="${KRW_GIT_PUSH_TOKEN:-}"
# One simple, explicit upgrade switch for previously installed Agents whose
# saved permissions are still 0. New installs default to 1 automatically.
ENABLE_DEFAULT_PERMISSIONS="${KRW_ENABLE_DEFAULT_PERMISSIONS:-0}"
[[ "$ENABLE_DEFAULT_PERMISSIONS" =~ ^[01]$ ]] || fail 'KRW_ENABLE_DEFAULT_PERMISSIONS must be 0 or 1'
STORED_DEVICE_ID=""
if [[ -f "$CONFIG_FILE" ]]; then
  [[ -O "$CONFIG_FILE" && ! -L "$CONFIG_FILE" ]]     || fail 'Existing Agent configuration is not an owner-owned regular file'
  # This file is generated by this installer, stored outside the workspace
  # with mode 0600, and is trusted as a local user configuration.
  # shellcheck disable=SC1090
  source "$CONFIG_FILE"
  STORED_DEVICE_ID="${KRW_DEVICE_ID:-}"
  info 'Reusing existing Agent configuration'
fi
if [[ -n "$STORED_DEVICE_ID" && -n "$OVERRIDE_DEVICE_ID" && "$STORED_DEVICE_ID" != "$OVERRIDE_DEVICE_ID" ]]; then
  fail 'Cannot change ID while reusing saved credentials; choose different KRW_CONFIG_DIR and KRW_INSTALL_DIR'
fi
[[ -n "$OVERRIDE_DEVICE_ID" ]] && KRW_DEVICE_ID="$OVERRIDE_DEVICE_ID"
[[ -n "$OVERRIDE_WORKSPACE" ]] && KRW_WORKSPACE_ROOT="$OVERRIDE_WORKSPACE"
[[ -n "$OVERRIDE_TOKEN" ]] && KRW_AGENT_TOKEN="$OVERRIDE_TOKEN"
[[ -n "$OVERRIDE_AUTO_ENROLL" ]] && KRW_AUTO_ENROLL="$OVERRIDE_AUTO_ENROLL"
[[ -n "$OVERRIDE_WRITES" ]] && KRW_ALLOW_FILE_WRITES="$OVERRIDE_WRITES"
[[ -n "$OVERRIDE_CHECKS" ]] && KRW_ALLOW_STATIC_CHECKS="$OVERRIDE_CHECKS"
[[ -n "$OVERRIDE_WORKSPACES" ]] && KRW_WORKSPACES_JSON="$OVERRIDE_WORKSPACES"
[[ -n "$OVERRIDE_GIT_WRITES" ]] && KRW_ALLOW_GIT_WRITES="$OVERRIDE_GIT_WRITES"
[[ -n "$OVERRIDE_GIT_PUSH" ]] && KRW_ALLOW_GIT_PUSH="$OVERRIDE_GIT_PUSH"
[[ -n "$OVERRIDE_TASKS" ]] && KRW_ALLOW_TASKS="$OVERRIDE_TASKS"
[[ -n "$OVERRIDE_TEST_TASKS" ]] && KRW_ALLOW_TEST_TASKS="$OVERRIDE_TEST_TASKS"
[[ -n "$OVERRIDE_LONG_TASKS" ]] && KRW_ALLOW_LONG_TASKS="$OVERRIDE_LONG_TASKS"
[[ -n "$OVERRIDE_CLI" ]] && KRW_ALLOW_CLI="$OVERRIDE_CLI"
[[ -n "$OVERRIDE_GIT_TOKEN" ]] && KRW_GIT_PUSH_TOKEN="$OVERRIDE_GIT_TOKEN"
if [[ "$ENABLE_DEFAULT_PERMISSIONS" == "1" ]]; then
  # Preserve explicit per-flag 0 overrides supplied on the installer command.
  # A simple upgrade command can intentionally enable all previous defaults.
  [[ -n "$OVERRIDE_WRITES" ]] || KRW_ALLOW_FILE_WRITES=1
  [[ -n "$OVERRIDE_CHECKS" ]] || KRW_ALLOW_STATIC_CHECKS=1
  [[ -n "$OVERRIDE_GIT_WRITES" ]] || KRW_ALLOW_GIT_WRITES=1
  [[ -n "$OVERRIDE_GIT_PUSH" ]] || KRW_ALLOW_GIT_PUSH=1
  [[ -n "$OVERRIDE_TASKS" ]] || KRW_ALLOW_TASKS=1
  [[ -n "$OVERRIDE_TEST_TASKS" ]] || KRW_ALLOW_TEST_TASKS=1
  [[ -n "$OVERRIDE_LONG_TASKS" ]] || KRW_ALLOW_LONG_TASKS=1
  info 'Enabling default Agent permissions; per-flag overrides remain supported'
fi
ALLOW_WRITES="${KRW_ALLOW_FILE_WRITES:-1}"
ALLOW_CHECKS="${KRW_ALLOW_STATIC_CHECKS:-1}"
ALLOW_GIT_WRITES="${KRW_ALLOW_GIT_WRITES:-1}"
ALLOW_GIT_PUSH="${KRW_ALLOW_GIT_PUSH:-1}"
ALLOW_TASKS="${KRW_ALLOW_TASKS:-1}"
ALLOW_TEST_TASKS="${KRW_ALLOW_TEST_TASKS:-1}"
ALLOW_LONG_TASKS="${KRW_ALLOW_LONG_TASKS:-1}"
# New arbitrary CLI capability requires explicit opt-in, never a default.
ALLOW_CLI="${KRW_ALLOW_CLI:-0}"
WORKSPACES_JSON="${KRW_WORKSPACES_JSON:-}"
[[ -n "$WORKSPACES_JSON" ]] || WORKSPACES_JSON="{}"
GIT_PUSH_TOKEN="${KRW_GIT_PUSH_TOKEN:-}"
[[ "$ALLOW_WRITES" =~ ^[01]$ && "$ALLOW_CHECKS" =~ ^[01]$ && "$ALLOW_GIT_WRITES" =~ ^[01]$ && "$ALLOW_GIT_PUSH" =~ ^[01]$ && "$ALLOW_TASKS" =~ ^[01]$ && "$ALLOW_TEST_TASKS" =~ ^[01]$ && "$ALLOW_LONG_TASKS" =~ ^[01]$ && "$ALLOW_CLI" =~ ^[01]$ ]]   || fail 'Agent permission flags must be 0 or 1'

DEVICE_ID="${KRW_DEVICE_ID:-}"
if [[ -z "$DEVICE_ID" ]]; then
  DEVICE_ID="$(python3 -c 'import uuid; print("agent-" + uuid.uuid4().hex)')"
  info "Generated device ID: $DEVICE_ID"
fi
[[ "$DEVICE_ID" =~ ^[a-z0-9][a-z0-9._-]{0,63}$ ]] || fail 'Invalid device ID'

WORKSPACE="${KRW_WORKSPACE_ROOT:-}"
if [[ -z "$WORKSPACE" ]]; then
  prompt WORKSPACE 'Workspace absolute path (e.g. /content/my-project): '
fi
[[ "$WORKSPACE" = /* && -d "$WORKSPACE" ]] || fail 'Workspace must be an existing absolute directory'
WORKSPACE="$(cd -- "$WORKSPACE" && pwd -P)"
[[ "$WORKSPACE" != '/' && "$WORKSPACE" != '/content' && "$WORKSPACE" != "$HOME" ]] \
  || fail 'Choose a dedicated workspace directory, not a broad filesystem root'

TOKEN="${KRW_AGENT_TOKEN:-}"
AUTO_ENROLL="${KRW_AUTO_ENROLL:-0}"
if [[ -z "$TOKEN" ]]; then
  TOKEN="$(python3 -c 'import secrets; print(secrets.token_urlsafe(32))')"
  AUTO_ENROLL=1
  info 'Generated a device-specific 256-bit secret (never printed).'
fi
[[ ${#TOKEN} -ge 32 ]] || fail 'KRW_AGENT_TOKEN must have at least 32 characters'
[[ "$AUTO_ENROLL" =~ ^[01]$ ]] || fail 'KRW_AUTO_ENROLL must be 0 or 1'

# Keep credentials outside the remotely readable workspace.
mkdir -p -- "$INSTALL_DIR" "$CONFIG_DIR"
INSTALL_DIR="$(cd -- "$INSTALL_DIR" && pwd -P)"
CONFIG_DIR="$(cd -- "$CONFIG_DIR" && pwd -P)"
case "$INSTALL_DIR/" in "$WORKSPACE/"*) fail 'Installation directory must be outside the workspace';; esac
case "$CONFIG_DIR/" in "$WORKSPACE/"*) fail 'Credentials directory must be outside the workspace';; esac
case "$WORKSPACE/" in "$INSTALL_DIR/"*) fail 'Workspace must not contain agent installation';; esac
case "$WORKSPACE/" in "$CONFIG_DIR/"*) fail 'Workspace must not contain credentials';; esac

TEMP_DIR="$(mktemp -d)"
trap 'rm -rf -- "$TEMP_DIR"' EXIT
ARCHIVE="$TEMP_DIR/agent-bundle.tar.gz"
info "Fetching Agent from $BASE_URL"
if command -v curl >/dev/null; then
  curl -fsSL --retry 2 --connect-timeout 15 --max-time 90 "$BASE_URL/agent-bundle.tar.gz" -o "$ARCHIVE"
elif command -v wget >/dev/null; then
  wget -qO "$ARCHIVE" "$BASE_URL/agent-bundle.tar.gz"
else
  fail 'curl or wget is required'
fi
printf '%s  %s\n' "$EXPECTED_SHA256" "$ARCHIVE" | sha256sum -c - >/dev/null \
  || fail 'Agent bundle checksum mismatch; nothing has been installed'

while IFS= read -r item; do
  case "$item" in
    agent/__init__.py|agent/agent.py|agent/worker.py|agent/git_readonly.py|agent/git_write.py|agent/workspace_routes.py|agent/task_runner.py|agent/long_tasks.py|agent/workspace_edit.py|agent/workspace_manage.py|agent-requirements.txt) ;;
    *) fail 'Unexpected file in Agent bundle' ;;
  esac
done < <(tar -tzf "$ARCHIVE")
tar -xzf "$ARCHIVE" -C "$INSTALL_DIR" --no-same-owner

# Colab sometimes has Python but cannot create a pip-enabled venv (ensurepip
# fails). Prefer a working venv; otherwise install libraries under an isolated
# --target directory without modifying the system-wide Python environment.
VENV_PYTHON="$INSTALL_DIR/.venv/bin/python"
AGENT_PYTHON=''
AGENT_EXTRA_PATH=''
if [[ -x "$VENV_PYTHON" ]] && "$VENV_PYTHON" -m pip --version >/dev/null 2>&1; then
  info 'Using existing Python virtual environment'
elif python3 -m venv "$INSTALL_DIR/.venv" >"$TEMP_DIR/venv.log" 2>&1 \
     && [[ -x "$VENV_PYTHON" ]] \
     && "$VENV_PYTHON" -m pip --version >/dev/null 2>&1; then
  info 'Created Python virtual environment'
else
  info 'Python venv/ensurepip unavailable; using isolated --target dependencies'
fi

if [[ -x "$VENV_PYTHON" ]] && "$VENV_PYTHON" -m pip --version >/dev/null 2>&1; then
  "$VENV_PYTHON" -m pip install --disable-pip-version-check -q \
    -r "$INSTALL_DIR/agent-requirements.txt" || fail 'Installing Agent requirements into venv failed'
  AGENT_PYTHON="$VENV_PYTHON"
else
  python3 -m pip --version >/dev/null 2>&1 \
    || fail 'Python pip is unavailable. Install python3-pip or use an environment with pip.'
  mkdir -p -- "$INSTALL_DIR/.packages"
  python3 -m pip install --disable-pip-version-check -q --upgrade \
    --target "$INSTALL_DIR/.packages" -r "$INSTALL_DIR/agent-requirements.txt" \
    || fail 'Installing Agent requirements into isolated target failed'
  AGENT_PYTHON="$(command -v python3)"
  AGENT_EXTRA_PATH="$INSTALL_DIR/.packages"
fi

CONFIG_FILE="$CONFIG_DIR/agent.env"
{
  printf 'KRW_DEVICE_ID=%q\n' "$DEVICE_ID"
  printf 'KRW_AGENT_TOKEN=%q\n' "$TOKEN"
  printf 'KRW_AUTO_ENROLL=%s\n' "$AUTO_ENROLL"
  printf 'KRW_WORKSPACE_ROOT=%q\n' "$WORKSPACE"
  printf 'KRW_RELAY_URL=%q\n' "$BASE_URL"
  printf 'KRW_COMMANDS_ENABLED=0\n'
  printf 'KRW_ALLOW_TEST_COMMANDS=0\n'
  printf 'KRW_ALLOW_FILE_WRITES=%s\n' "$ALLOW_WRITES"
  printf 'KRW_ALLOW_STATIC_CHECKS=%s\n' "$ALLOW_CHECKS"
  printf 'KRW_WORKSPACES_JSON=%q\n' "$WORKSPACES_JSON"
  printf 'KRW_ALLOW_GIT_WRITES=%s\n' "$ALLOW_GIT_WRITES"
  printf 'KRW_ALLOW_GIT_PUSH=%s\n' "$ALLOW_GIT_PUSH"
  printf 'KRW_ALLOW_TASKS=%s\n' "$ALLOW_TASKS"
  printf 'KRW_ALLOW_TEST_TASKS=%s\n' "$ALLOW_TEST_TASKS"
  printf 'KRW_ALLOW_LONG_TASKS=%s\n' "$ALLOW_LONG_TASKS"
  printf 'KRW_ALLOW_CLI=%s\n' "$ALLOW_CLI"
  if [[ -n "$GIT_PUSH_TOKEN" ]]; then
    printf 'KRW_GIT_PUSH_TOKEN=%q\n' "$GIT_PUSH_TOKEN"
  fi
} >"$CONFIG_FILE"
chmod 600 "$CONFIG_FILE"
unset TOKEN KRW_AGENT_TOKEN

printf '#!/usr/bin/env bash\nCONFIG_FILE=%q\nAGENT_PYTHON=%q\nAGENT_EXTRA_PATH=%q\n' \
  "$CONFIG_FILE" "$AGENT_PYTHON" "$AGENT_EXTRA_PATH" > "$INSTALL_DIR/start.sh"
cat >> "$INSTALL_DIR/start.sh" <<'RUNNER'
set -euo pipefail
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
[[ -f "$CONFIG_FILE" ]] || { echo 'KRW agent configuration missing' >&2; exit 1; }
set -a
source "$CONFIG_FILE"
set +a
export KRW_COMMANDS_ENABLED=0 KRW_ALLOW_TEST_COMMANDS=0
cd "$SCRIPT_DIR"
if [[ -n "$AGENT_EXTRA_PATH" ]]; then
  export PYTHONPATH="$AGENT_EXTRA_PATH${PYTHONPATH:+:$PYTHONPATH}"
fi
exec "$AGENT_PYTHON" -m agent.agent
RUNNER
chmod 700 "$INSTALL_DIR/start.sh"
info "Ready: device=$DEVICE_ID workspace=$WORKSPACE"
info "Rerun later with: $INSTALL_DIR/start.sh"
info 'Starting Agent (Ctrl+C stops it)'
rm -rf -- "$TEMP_DIR"
trap - EXIT
exec "$INSTALL_DIR/start.sh"
